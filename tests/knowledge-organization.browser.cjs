const assert = require('node:assert/strict')
const fs = require('node:fs')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
  const browser=await chromium.launch({headless:true,...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})})
  try {
    const page=await browser.newPage({viewport:{width:1440,height:1000},serviceWorkers:'block'})
    const errors=[];page.on('pageerror',e=>errors.push(e.message))
    await page.goto('http://127.0.0.1:19691/dash/#/Knowledge')
    await page.getByLabel('Password').fill('knowledge-preview')
    await page.getByRole('button',{name:'Entra',exact:true}).click()
    await page.getByRole('heading',{name:'Documentazione e studi'}).waitFor()
    await page.getByRole('tab',{name:'Esplora documenti',exact:true}).click()
    await page.getByLabel('Filtra titolo o percorso').fill('bt-strategy-test/RMA/study_20261020/README.md')
    const row=page.locator('.q-item').filter({has:page.getByText('bt-strategy-test/RMA/study_20261020/README.md',{exact:true})})
    await row.getByText('RMA',{exact:true}).waitFor()
    await page.getByText('bt-strategy-test/RMA/study_20261020/README.md',{exact:true}).click()
    await page.locator('.source-dialog .line-number').first().waitFor()
    await page.getByRole('switch',{name:'Testo formattato',exact:true}).click()
    await page.locator('.knowledge-markdown h1').waitFor()
    await page.waitForTimeout(350)
    const typography=await page.locator('.knowledge-markdown').evaluate(el=>({
      h1:parseFloat(getComputedStyle(el.querySelector('h1')).fontSize),
      h2:parseFloat(getComputedStyle(el.querySelector('h2')).fontSize),
      pre:getComputedStyle(el.querySelector('pre')).backgroundColor,
      code:getComputedStyle(el.querySelector('code')).backgroundColor,
      height:el.scrollHeight,
    }))
    assert.ok(typography.h1<=28 && typography.h2<=24)
    assert.notEqual(typography.pre,'rgba(0, 0, 0, 0)')
    const reference=page.locator('.knowledge-markdown a[data-source="bt-strategy-test/RMA/study_20261020/decisions/P2_P3_PRECOMMITTED_DESIGN.md"]').first()
    await reference.waitFor()
    await reference.click()
    await page.locator('.source-dialog').getByText('P2/P3 finite design',{exact:true}).first().waitFor()
    await page.locator('.knowledge-markdown h1').waitFor()
    assert.match(await page.locator('.source-dialog').innerText(),/Documento completo/)
    await page.getByRole('button',{name:'Fonte precedente',exact:true}).click()
    await page.locator('.source-dialog .wrap-path').filter({hasText:'bt-strategy-test/RMA/study_20261020/README.md'}).first().waitFor()
    await page.locator('.knowledge-markdown a[data-source="bt-strategy-test/RMA/study_20261020/reports/FINAL_REPORT.md"]').first().click()
    const bare=page.locator('.knowledge-markdown code a[data-source="docs/context/strategy-analysis.md"]').first()
    await bare.waitFor();await bare.click()
    await page.locator('.source-dialog .wrap-path').filter({hasText:'docs/context/strategy-analysis.md'}).first().waitFor()
    await page.getByRole('button',{name:'Fonte precedente',exact:true}).click()
    await page.locator('.knowledge-markdown code a[data-source="docs/context/strategy-analysis.md"]').first().waitFor()
    await page.getByRole('button',{name:'Fonte precedente',exact:true}).click()
    await page.locator('.source-dialog .wrap-path').filter({hasText:'bt-strategy-test/RMA/study_20261020/README.md'}).first().waitFor()
    await page.locator('.knowledge-markdown h1').filter({hasText:'RMAStrategy: studio isolato'}).waitFor()
    await page.waitForTimeout(350)
    await page.screenshot({path:'/tmp/bt-knowledge-v2-reader.png',fullPage:true})
    await page.getByRole('button',{name:'Chiudi fonte',exact:true}).click()
    await page.getByRole('tab',{name:'Run',exact:true}).click()
    await page.getByRole('button',{name:'Cerca run',exact:true}).waitFor()
    const response=await page.request.get('http://127.0.0.1:19691/api/dyn/knowledge/status')
    const status=await response.json();assert.ok(status.runs.runs>12000)
    await page.getByLabel('Cerca nei run',{exact:true}).fill('post_up_cooldown_days')
    await page.getByRole('button',{name:'Cerca run',exact:true}).click()
    await page.locator('.q-list .q-item').filter({hasText:'Parametri effettivi dall’artefatto'}).first().waitFor()
    const runResponse=page.waitForResponse(r=>r.url().includes('/knowledge/run?id='))
    await page.locator('.q-list .q-item').filter({hasText:'Parametri effettivi dall’artefatto'}).first().click()
    const run=await (await runResponse).json()
    assert.ok(Object.keys(run.resolved_parameters).length)
    await page.getByText('Configurazioni richieste, distinte dai parametri effettivi',{exact:true}).waitFor()
    await page.setViewportSize({width:390,height:844});await page.waitForTimeout(350)
    await page.screenshot({path:'/tmp/bt-knowledge-v2-run-mobile.png',fullPage:true})
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false)
    await page.getByRole('button',{name:'Chiudi run',exact:true}).click()
    const search=await page.request.get('http://127.0.0.1:19691/api/dyn/knowledge/runs',{params:{q:'RMA medie alternative',mode:'semantic',limit:5,filters:JSON.stringify({strategy_family:'RMA'})},timeout:120000})
    assert.equal(search.status(),200)
    const semantic=await search.json();assert.ok(semantic.runs.length);assert.ok(semantic.runs.every(r=>r.strategy_family==='RMA'))
    assert.deepEqual(errors,[])
    const result={document_types_assigned:true,strategy_visible:true,heading_sizes:typography,gray_code_blocks:true,
      clickable_bare_document_references:true,source_back_navigation:true,full_formatted_document:true,
      catalog_runs:status.runs.runs,run_parameters_distinct_from_requests:true,semantic_run_filter:true,
      mobile_no_horizontal_overflow:true,javascript_errors:errors}
    fs.writeFileSync('/tmp/bt-knowledge-v2-browser-result.json',JSON.stringify(result,null,2));console.log(JSON.stringify(result))
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
